#[test]
fn configuration_decal_complete_managers_match_independent_oracles_and_bytes() {
    for (bytes, oracle, reads) in MANAGERS {
        let parsed = super::manager_context_tests::decode(bytes).unwrap();
        super::manager_oracle_tests::assert_reference_fields(&parsed.fields, bytes, oracle, *reads);
        assert_eq!(encode_fields(&parsed.fields, 30000).unwrap(), *bytes);
    }
}
#[test]
fn configuration_decal_owned_edits_match_all_ten_independent_goldens() {
    for kind in 0..10 {
        let mut parsed = super::manager_context_tests::decode(MANAGERS[kind * 6 + 2].0).unwrap();
        parsed
            .fields
            .iter_mut()
            .find(|f| f.path.ends_with(".owned_6d8.objects[0].decal.raw_48"))
            .unwrap()
            .value = ModelFieldValue::I32(12345);
        assert_eq!(
            encode_fields(&parsed.fields, 30000).unwrap(),
            MANAGERS[60 + kind].0
        );
    }
}
#[test]
fn configuration_decal_owned_managers_reject_every_prefix_and_appended_byte() {
    for (bytes, _, _) in MANAGERS {
        for end in 0..bytes.len() {
            assert!(super::manager_context_tests::decode(&bytes[..end]).is_err());
        }
        let mut extra = bytes.to_vec();
        extra.push(0);
        assert!(super::manager_context_tests::decode(&extra).is_err());
    }
}
