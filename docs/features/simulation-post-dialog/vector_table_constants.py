"""Deterministic production table data from hash-bound C-879 constant outputs (#166)."""
from typing import cast
from pathlib import Path
import struct
import sys
from dialog_evidence import FEATURE, dialog_baseline
from native_carriers import digest, RESEARCH
from vector_evidence import vector_reports


def vector_table_source(report: dict[str, object]) -> str:
    """Render only verified raw table data, preserving each component index for review; e.g. vector_table_source(report)."""
    tables = cast(list[dict[str, object]], report['tables'])
    patterns = sorted({entry['output_raw_hex'] for table in tables for entry in cast(list[dict[str, object]], table['entries'])})
    assert len(patterns) == 9 and sum(cast(int, table['count']) for table in tables) == 262
    lines = ['//! C-879 static table outputs; generated by vector_table_constants.py and verified against installed bytes (#166).',
        'pub(super) const OUTPUT_PATTERNS: [[u32; 4]; 9] = [']
    for raw in patterns:
        words = struct.unpack('<4I', bytes.fromhex(cast(str, raw)))
        lines.append('    [' + ', '.join(f'0x{word:08x}' for word in words) + '],')
    lines.extend(['];', '', 'pub(super) const TABLE_INDICES: [(u32, &[u8]); 23] = ['])
    for table in tables:
        entries = cast(list[dict[str, object]], table['entries'])
        assert [entry['component_index'] for entry in entries] == list(range(cast(int, table['count'])))
        indices = ''.join(str(patterns.index(entry['output_raw_hex'])) for entry in entries)
        lines.append(f'    ({int(cast(str, table["rva"]), 16):#010x}, b"{indices}"),')
    return '\n'.join(lines + ['];', ''])


def verify_vector_table_constants() -> None:
    """Require complete production constants to match the independent static evidence; e.g. verify_vector_table_constants()."""
    report = vector_reports()[1]
    generated = vector_table_source(report).encode()
    target = FEATURE.parents[2] / 'src/simulation/persistence/post_vector/tables.rs'
    if '--write' in sys.argv: target.write_bytes(generated)
    assert target.read_bytes() == generated, f'{target}; expected all 23 tables and 262 independently bound outputs'
    dialog_baseline('vector-table-constants-reference.json', dict(tables=23, entries=262, unique_outputs=9,
        bytes=len(generated), sha256=digest(generated), additional_stored_byte_credit=0))


def pinned_vector_data(pin: Path, *, copy: bool) -> None:
    """Copy the real table dependency once and verify it again after replay; e.g. pinned_vector_data(pin, copy=True)."""
    filename = 'cosworks-component-vector-tables-evidence.json'
    expected = '1933efb29a13b5d1ca6ca18e07b37a6a612b5c9dd52a476f16459eb416a41311'
    destination = pin / 'research' / filename
    if copy:
        raw = (RESEARCH / filename).read_bytes()
        assert digest(raw) == expected, (filename, digest(raw))
        destination.write_bytes(raw)
    raw = destination.read_bytes()
    assert digest(raw) == expected, (filename, digest(raw))
    dialog_baseline('vector-data-snapshot.json', dict(path='research/' + filename,
        bytes=len(raw), sha256=expected, immutable_before_and_after_replay=True))
